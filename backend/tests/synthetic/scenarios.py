def clean_a(respondent_id: str, **overrides) -> SheetFill:
    """CLEAN_A with MATRICOLA ``digits(respondent_id)``.

    *overrides* replace a label's marks or text (``None`` removes the label);
    hyphenated labels go through ``**{"M-RIGHE": ...}``.
    """
    answers = dict(CLEAN_A.answers)
    cells = {**CLEAN_A.cells, "MATRICOLA": digits(respondent_id)}
    texts = dict(CLEAN_A.texts)
    for label, value in overrides.items():
        if label in answers:
            target = answers
        elif label in cells:
            target = cells
        elif label in texts:
            target = texts
        else:
            raise KeyError(f"clean_a: unknown label {label!r}")
        if value is None:
            del target[label]
        else:
            target[label] = value
    return SheetFill(answers=answers, cells=cells, texts=texts)


def clean_a_readings(
    respondent_id: str | RespondentIdReading, **overrides: Reading | None
) -> dict[str, Reading]:
    """CLEAN_A_READINGS plus the MATRICOLA, with *overrides* (``None`` removes)."""
    if isinstance(respondent_id, str):
        respondent_id = RespondentIdReading(respondent_id)
    readings = {**CLEAN_A_READINGS, "MATRICOLA": respondent_id}
    for label, value in overrides.items():
        if label not in readings:
            raise KeyError(f"clean_a_readings: unknown label {label!r}")
        if value is None:
            del readings[label]
        else:
            readings[label] = value
    return readings


def _cells_plus(label: str, *extra: tuple[int, int]) -> tuple[tuple[int, int], ...]:
    return CLEAN_A_CELLS[label] + extra


