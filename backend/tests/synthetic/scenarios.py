# Maximum of each variant (worked out by hand from specs.py): Q01–Q04,
# Q07–Q12 single choice 1 each; Q05, Q06 multiple choice 2 each (two options
# of four at +1); M-RIGHE 4 rows × 1, M-COLONNE 4 columns × 1, M-MULTI 3 rows
# × 2. MATRICOLA, free texts and codes do not score.
MAX_A = 28.0  # 10 + 4 + 4 + 4 + 6; B the same
MAX_C = 27.0  # A without Q12
MAX_SINGLE = 8.0  # Q01–Q04 + Q05, Q06


def _score(points: float, max: float = MAX_A) -> ExpectedScore:
    return ExpectedScore(points, max)


_FREE_TEXT_REVIEW = {
    "NOME": frozenset({ALWAYS_REVIEW}),
    "APERTA": frozenset({ALWAYS_REVIEW}),
}
_FREE_TEXTS = ("NOME", "APERTA")
_ALL_PAGES = ((1, CODE, DECLARED), (2, CODE, DECLARED), (3, CODE, DECLARED))
_INVALID = frozenset({INVALID_ANSWER})


def _expected(**kwargs) -> Expected:
    kwargs.setdefault("variant", "A")
    kwargs.setdefault("free_texts", _FREE_TEXTS)
    return Expected(status=SubmissionStatus.SCANNED, **kwargs)


def _scenario(id: str, description: str, fill: SheetFill, expected: Expected,
              seed: int, project: str = "MULTI", variant: str = "A",
              extra_sheets: tuple[ExtraSheet, ...] = (), **options) -> Scenario:
    return Scenario(
        id=id, description=description, project=project, variant=variant,
        fill=fill, options=SheetOptions(seed=seed, **options), expected=expected,
        extra_sheets=extra_sheets,
    )


