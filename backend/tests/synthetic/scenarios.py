"""End-to-end scenarios of the test kit.

Each ``Scenario`` is a filled-in sheet described declaratively (``SheetFill`` +
``SheetOptions``) with what the app must make of it written right next to it
(``Expected``). ``tests.synthetic.runner`` feeds the sheet through the app's
real path and compares.

The expectations are hand-written, never adapted to what the app does today. A
known app bug that makes a check observe something else is declared as a
``Deviation`` on that check's key, with the issue that tracks it; the runner
fails as soon as the bug is fixed, so the deviation gets removed.

Check keys: ``"candidate"``, ``"review:<LABEL>"``, ``"reading:<LABEL>"``,
``"no_results:<LABEL>"``, ``"score"``. A label read on more than one sheet is keyed
``"<LABEL>@<template page>"``, and ``"<LABEL>@<template page>#<sheet>"`` when
two sheets sit on the same template page (sheet = physical position from 1).
"""
from __future__ import annotations

from dataclasses import dataclass, field, replace

from app.models.enums import PageOrderSource, SubmissionStatus, Validity
from tests.synthetic.generator import MarkStyle, SheetFill, SheetOptions, digits

# flag_reasons codes (app.services.submission_review_service)
ALWAYS_REVIEW = "ALWAYS_REVIEW"
INVALID_ANSWER = "INVALID_ANSWER"
AMBIGUOUS_DIGITS = "AMBIGUOUS_DIGITS"
