# SubmissionPage.match_confidence (submission_matching_service)
DECLARED = 1.0  # the sheet's VID declared its page
DEDUCED = 0.5   # physical position
UNPLACED = 0.0  # no page of the variant for it


# ---------------------------------------------------------------------------
# Dataclasses
# ---------------------------------------------------------------------------


@dataclass(frozen=True)
class QuestionReading:
    letters: tuple[str, ...]  # letters printed on the variant, alphabetical
    validity: Validity


@dataclass(frozen=True)
class MatrixReading:
    cells: frozenset[tuple[int, int]]  # (row, column) read as selected
    # Indices of the groups (rows or columns, per the selection rule) whose
    # validity is not VALID.
    invalid_groups: frozenset[int] = frozenset()


@dataclass(frozen=True)
class RespondentIdReading:
    raw_value: str
    ambiguous_columns: tuple[int, ...] = ()


@dataclass(frozen=True)
class CodeReading:
    decoded_value: str | None
    decode_successful: bool


Reading = QuestionReading | MatrixReading | RespondentIdReading | CodeReading


@dataclass(frozen=True)
class Deviation:
    issue: str        # e.g. "#123", the issue tracking the bug
    observed: object  # what the check observes TODAY because of the bug


@dataclass(frozen=True)
class ExpectedScore:
    """The score of the submission after extraction, worked out by hand from
    the answer key (``specs.py``) and the scoring rules: an object in review
    is pending and scores 0. The percentage is derived."""
    points: float
    max: float


# Per sheet, physical order: (template page or None, order source,
# match_confidence or None when matching never examined the sheet).
PageExpectation = tuple[int | None, PageOrderSource, float | None]


@dataclass(frozen=True)
class Expected:
    status: SubmissionStatus                        # after extraction
    variant: str | None                             # variant key, None = not matched
    candidate: str | None
    missing_pages: tuple[int, ...]
    pages: tuple[PageExpectation, ...]
    review: dict[str, frozenset[str]]               # EXACT labels in review → flag_reasons
    readings: dict[str, Reading]
    # No default: every scenario declares it. None = no score, a submission
    # never extracted.
    score: ExpectedScore | None
    free_texts: tuple[str, ...] = ()                # result + non-empty suggestion
    # Labels with NO result at all, on any sheet (a role-bound VID is consumed
    # by matching, never read as an answer).
    no_results: tuple[str, ...] = ("VID",)
    deviations: dict[str, Deviation] = field(default_factory=dict)
    status_after_upload: SubmissionStatus = SubmissionStatus.MATCHED


@dataclass(frozen=True)
class ExtraSheet:
    """One page of ANOTHER filled-in submission, appended after the scenario's
    own sheets (F19): generated by the runner, which needs the database."""
    variant: str
    fill: SheetFill
    options: SheetOptions
    page: int


@dataclass(frozen=True)
class Scenario:
    id: str
    description: str
    project: str  # "MULTI" | "SINGLE"
    variant: str  # the variant the sheets were printed from, e.g. "A"
    fill: SheetFill
    options: SheetOptions
    expected: Expected
    extra_sheets: tuple[ExtraSheet, ...] = ()
    # Loose images (G01, G02): one filename per generated sheet, in upload
    # order; empty = uploaded as one PDF.
    image_names: tuple[str, ...] = ()


