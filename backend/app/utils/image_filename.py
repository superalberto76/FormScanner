"""The loose-image upload naming convention.

A scanner that emits one image per sheet loses the two things a PDF gives for
free: which sheets form one submission, and in what order. When a sheet carries
a printed RID/VID code, ingestion needs neither — the code says so itself. This
module implements the FALLBACK for sheets whose codes will not decode:

    <submission>_page_<n>.<ext>

``_pagina_`` is accepted as an equivalent separator, under the same rules.

Deliberately a pure syntax parser with no ORM, no filesystem and no HTTP —
mirroring how ``code_rendering.parse_tagged_payload`` parses the *other* signal
source. Which signal wins for grouping or for ordering is a policy decision and
lives in ``submission_identification_service``, not here.

Like every parser on the ingestion path this one is TOTAL: a non-conformant name
returns None, never raises. An operator who names a file badly must not be able
to fail an upload.
"""
from __future__ import annotations

import re
from pathlib import PurePath

# The literals separating the grouping token from the page number, matched
# case-insensitively (``_PAGE_`` is as valid as ``_page_``). The two are
# equivalent: whichever occurs LAST in the name is the split point.
PAGE_SEPARATORS = ("_page_", "_pagina_")

# The page number: digits only. Zero padding IS allowed (``_page_007`` -> 7)
# because scanners routinely zero-pad and a filename is typed by a human or a
# device, not generated by our own exporter. This is deliberately looser than
# ``code_rendering.parse_payload``, which round-trips a machine-generated payload
# and therefore rejects "007". A sign, whitespace or a decimal point is NOT
# allowed — those are not "a padded number", they are a different name.
_PAGE_NUMBER_RE = re.compile(r"^\d+$")


def parse_image_filename(filename: str) -> tuple[str, int] | None:
    """Split a client filename into ``(submission_token, page_index_0_based)``.

    Returns None when *filename* does not follow ``<submission>_page_<n>.<ext>``
    (or the equivalent ``<submission>_pagina_<n>.<ext>``).

    Rules (all pinned by tests):

      * case-insensitive on the separator and on the extension; the
        ``<submission>`` token KEEPS its case — it is a grouping key, so
        submissions deliberately named ``A`` and ``a`` must stay distinct;
      * the LAST separator, of either kind, is the split point, so the grouping
        token may itself contain one (``test_page_green_page_2.jpg`` ->
        ``("test_page_green", 1)``, ``test_page_green_pagina_2.jpg`` ->
        ``("test_page_green", 1)``);
      * ``<n>`` is 1-BASED and must be >= 1; the returned index is 0-BASED, ready
        for ``SubmissionPage.source_page_order``. ``_page_0`` is not
        conformant — there is no page zero to convert;
      * the extension is neither required nor validated. What a file really IS
        comes from content sniffing, never from its name;
      * directory components are stripped first, so a client cannot smuggle a
        path in. (The name never reaches the filesystem regardless: a page image
        is stored under its SubmissionPage id.)
    """
    if not isinstance(filename, str):
        return None

    # Strip any directory component before anything else, then the extension.
    name = PurePath(filename).name
    if not name:
        return None
    stem = PurePath(name).stem if PurePath(name).suffix else name

    # Search a case-folded copy so the split point is found case-insensitively
    # while the returned token keeps its ORIGINAL case. The two separators
    # cannot overlap ("_page_" is not a substring of "_pagina_"), so the
    # rightmost match of either is unambiguous.
    lowered = stem.lower()
    position, separator = max(
        (lowered.rfind(candidate), candidate) for candidate in PAGE_SEPARATORS
    )
    if position == -1:
        return None

    token = stem[:position]
    number = stem[position + len(separator):]
    if not token or not _PAGE_NUMBER_RE.match(number):
        return None

    page_number = int(number)
    if page_number < 1:  # 1-based by definition; there is no page zero
        return None
    return token, page_number - 1
